package http

import (
	"database/sql"
	"net/http"
	"time"

	"github.com/go-chi/chi/v5"
	"github.com/redis/go-redis/v9"
	"github.com/sirupsen/logrus"
	"go-repair-center/internal/platform/config"
	platjwt "go-repair-center/internal/platform/jwt"
	"go-repair-center/internal/repository/mysql"
	"go-repair-center/internal/service"
	"go-repair-center/internal/transport/http/handler"
	"go-repair-center/internal/transport/http/middleware"
)

func NewRouter(cfg *config.Config, db *sql.DB, redisClient *redis.Client, log *logrus.Logger) http.Handler {
	jwtManager := platjwt.NewManager(cfg.JWTSecret, cfg.JWTAccessTTL, cfg.JWTRefreshTTL)
	userRepo := mysql.NewUserRepository(db)
	analyticsRepo := mysql.NewAnalyticsRepo(db)
	partRepo := mysql.NewPartRepository(db)
	quotationRepo := mysql.NewQuotationRepository(db)
	customerRepo := mysql.NewCustomerRepository(db)
	deviceRepo := mysql.NewDeviceRepository(db)
	repairOrderRepo := mysql.NewRepairOrderRepository(db)
	repairExecutionRepo := mysql.NewRepairExecutionRepository(db)
	warrantyRepo := mysql.NewWarrantyRepository(db)
	feedbackRepo := mysql.NewFeedbackRepository(db)
	auditRepo := mysql.NewAuditRepository(db)
	permissionRepo := mysql.NewPermissionRepository(db)
	roleRepo := mysql.NewRoleRepository(db)
	systemConfigRepo := mysql.NewSystemConfigRepository(db)
	faultCodeRepo := mysql.NewFaultCodeRepository(db)
	paymentRepo := mysql.NewPaymentRecordRepository(db)
	repairProcedureRepo := mysql.NewRepairProcedureRepository(db)
	repairTestRepo := mysql.NewRepairTestRecordRepository(db)
	feedbackScoreRepo := mysql.NewFeedbackScoreRepository(db)
	partStockLogRepo := mysql.NewPartStockLogRepository(db)

	authSvc := service.NewAuthService(userRepo, redisClient, jwtManager, cfg.LoginMaxAttempts, cfg.LoginLockoutDuration)
	userSvc := service.NewUserService(userRepo)
	customerSvc := service.NewCustomerService(customerRepo)
	deviceSvc := service.NewDeviceService(deviceRepo)
	repairOrderSvc := service.NewRepairOrderService(repairOrderRepo)
	quotationSvc := service.NewQuotationService(quotationRepo, cfg.QuotationValidDays, cfg.QuotationApprovalThreshold)
	repairExecutionSvc := service.NewRepairExecutionService(repairExecutionRepo)
	partSvc := service.NewPartService(partRepo)
	warrantySvc := service.NewWarrantyService(warrantyRepo)
	feedbackSvc := service.NewFeedbackService(feedbackRepo)
	auditSvc := service.NewAuditService(auditRepo)
	roleSvc := service.NewRoleService(roleRepo)
	permissionSvc := service.NewPermissionService(permissionRepo)
	systemConfigSvc := service.NewSystemConfigService(systemConfigRepo)
	faultCodeSvc := service.NewFaultCodeService(faultCodeRepo)
	paymentSvc := service.NewPaymentRecordService(paymentRepo)
	repairProcedureSvc := service.NewRepairProcedureService(repairProcedureRepo)
	repairTestSvc := service.NewRepairTestRecordService(repairTestRepo)
	feedbackScoreSvc := service.NewFeedbackScoreService(feedbackScoreRepo)
	partStockLogSvc := service.NewPartStockLogService(partStockLogRepo)
	cacheSvc := service.NewCacheService(redisClient, 5*time.Minute)
	dashboardSvc := service.NewDashboardService(analyticsRepo, cacheSvc)
	reportSvc := service.NewReportService(analyticsRepo, cacheSvc)
	opsSvc := service.NewOpsService(db)
	maintenanceSvc := service.NewMaintenanceService(db, cacheSvc)
	sessionSvc := service.NewSessionService(db, cacheSvc)
	importSvc := service.NewImportService()
	exportSvc := service.NewExportService()
	orderNumberSvc := service.NewOrderNumberService()
	notificationSvc := service.NewNotificationService(cacheSvc)
	approvalSvc := service.NewApprovalService(cfg.QuotationApprovalThreshold, cfg.WarrantyDefaultDays)
	dispatchSvc := service.NewDispatchService(db, opsSvc, orderNumberSvc, notificationSvc)
	approvalCenterSvc := service.NewApprovalCenterService(db, approvalSvc)
	inventoryControlSvc := service.NewInventoryControlService(db, partSvc)

	r := chi.NewRouter()
	r.Use(middleware.Recovery(log))
	r.Use(middleware.Logger(log))
	r.Use(middleware.CORS)
	r.Get("/health", func(w http.ResponseWriter, r *http.Request) {
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write([]byte("ok"))
	})
	r.Route("/api/v1", func(api chi.Router) {
		authHandler := handler.NewAuthHandler(authSvc)
		dashboardHandler := handler.NewDashboardHandler(dashboardSvc)
		reportHandler := handler.NewReportHandler(reportSvc)
		operationsHandler := handler.NewOperationsHandler(opsSvc, maintenanceSvc)
		sessionHandler := handler.NewSessionHandler(sessionSvc)
		dataToolsHandler := handler.NewDataToolsHandler(importSvc, exportSvc, customerSvc, deviceSvc, partSvc, repairOrderSvc, feedbackSvc, auditSvc)
		userHandler := handler.NewUserHandler(userSvc)
		customerHandler := handler.NewCustomerHandler(customerSvc)
		deviceHandler := handler.NewDeviceHandler(deviceSvc)
		repairOrderHandler := handler.NewRepairOrderHandler(repairOrderSvc)
		quotationHandler := handler.NewQuotationHandler(quotationSvc)
		repairExecutionHandler := handler.NewRepairExecutionHandler(repairExecutionSvc)
		partHandler := handler.NewPartHandler(partSvc)
		warrantyHandler := handler.NewWarrantyHandler(warrantySvc)
		feedbackHandler := handler.NewFeedbackHandler(feedbackSvc)
		auditHandler := handler.NewAuditHandler(auditSvc)
		roleHandler := handler.NewRoleHandler(roleSvc)
		permissionHandler := handler.NewPermissionHandler(permissionSvc)
		systemConfigHandler := handler.NewSystemConfigHandler(systemConfigSvc)
		faultCodeHandler := handler.NewFaultCodeHandler(faultCodeSvc)
		paymentHandler := handler.NewPaymentRecordHandler(paymentSvc)
		repairProcedureHandler := handler.NewRepairProcedureHandler(repairProcedureSvc)
		repairTestHandler := handler.NewRepairTestRecordHandler(repairTestSvc)
		feedbackScoreHandler := handler.NewFeedbackScoreHandler(feedbackScoreSvc)
		partStockLogHandler := handler.NewPartStockLogHandler(partStockLogSvc)
		dispatchCenterHandler := handler.NewDispatchCenterHandler(dispatchSvc)
		approvalCenterHandler := handler.NewApprovalCenterHandler(approvalCenterSvc)
		inventoryControlHandler := handler.NewInventoryControlHandler(inventoryControlSvc)
		api.Post("/auth/register", authHandler.Register)
		api.Post("/auth/login", authHandler.Login)
		api.Post("/auth/refresh", authHandler.Refresh)
		api.With(middleware.Auth(jwtManager)).Post("/auth/logout", authHandler.Logout)
		api.With(middleware.Auth(jwtManager)).Get("/me", authHandler.Me)
		api.With(middleware.Auth(jwtManager)).Post("/auth/password", authHandler.ChangePassword)
		api.With(middleware.Auth(jwtManager)).Get("/dashboard", dashboardHandler.Summary)
		api.With(middleware.Auth(jwtManager), middleware.Require("audit:read")).Get("/reports/revenue", reportHandler.Revenue)
		api.With(middleware.Auth(jwtManager), middleware.Require("audit:read")).Get("/reports/revenue.csv", reportHandler.RevenueCSV)
		api.With(middleware.Auth(jwtManager), middleware.Require("audit:read")).Get("/ops/backlog", operationsHandler.Backlog)
		api.With(middleware.Auth(jwtManager), middleware.Require("audit:read")).Get("/ops/sla-alerts", operationsHandler.SLAAlerts)
		api.With(middleware.Auth(jwtManager), middleware.Require("audit:read")).Get("/ops/warranty-expiring", operationsHandler.WarrantyExpiring)
		api.With(middleware.Auth(jwtManager), middleware.Require("audit:read")).Get("/ops/health", operationsHandler.HealthSnapshot)
		api.Group(func(tools chi.Router) {
			tools.Use(middleware.Auth(jwtManager))
			sessionHandler.Routes(tools)
			dataToolsHandler.Routes(tools)
		})

		api.Group(func(secured chi.Router) {
			secured.Use(middleware.Auth(jwtManager))
			userHandler.Routes(secured)
			customerHandler.Routes(secured)
			deviceHandler.Routes(secured)
			repairOrderHandler.Routes(secured)
			quotationHandler.Routes(secured)
			repairExecutionHandler.Routes(secured)
			partHandler.Routes(secured)
			warrantyHandler.Routes(secured)
			feedbackHandler.Routes(secured)
			auditHandler.Routes(secured)
			roleHandler.Routes(secured)
			permissionHandler.Routes(secured)
			systemConfigHandler.Routes(secured)
			faultCodeHandler.Routes(secured)
			paymentHandler.Routes(secured)
			repairProcedureHandler.Routes(secured)
			repairTestHandler.Routes(secured)
			feedbackScoreHandler.Routes(secured)
			partStockLogHandler.Routes(secured)
			dispatchCenterHandler.Routes(secured)
			approvalCenterHandler.Routes(secured)
			inventoryControlHandler.Routes(secured)
		})
	})
	return r
}
