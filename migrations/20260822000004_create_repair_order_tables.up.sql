CREATE TABLE IF NOT EXISTS repair_orders (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  order_number VARCHAR(64) NOT NULL,
  customer_id BIGINT UNSIGNED NOT NULL,
  device_id BIGINT UNSIGNED NOT NULL,
  original_order_id BIGINT UNSIGNED NULL,
  fault_description TEXT NOT NULL,
  urgency VARCHAR(32) NOT NULL DEFAULT 'NORMAL',
  service_method VARCHAR(32) NOT NULL DEFAULT 'ON_SITE',
  expected_completed_at DATETIME NULL,
  appointment_time DATETIME NULL,
  appointment_end DATETIME NULL,
  technician_id BIGINT UNSIGNED NULL,
  dispatched_at DATETIME NULL,
  notification_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  idempotency_key VARCHAR(64) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_repair_orders_order_number (order_number),
  UNIQUE KEY uk_repair_orders_idempotency_key (idempotency_key),
  KEY idx_repair_orders_status (status),
  KEY idx_repair_orders_created_at (created_at),
  KEY idx_repair_orders_appointment_time (appointment_time),
  KEY idx_repair_orders_deleted_at (deleted_at),
  CONSTRAINT fk_repair_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repair_orders_device FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repair_orders_original FOREIGN KEY (original_order_id) REFERENCES repair_orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repair_orders_technician FOREIGN KEY (technician_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS repair_order_status_histories (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  repair_order_id BIGINT UNSIGNED NOT NULL,
  from_status VARCHAR(32) NOT NULL,
  to_status VARCHAR(32) NOT NULL,
  reason VARCHAR(255) NOT NULL DEFAULT '',
  changed_by BIGINT UNSIGNED NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_repair_order_status_histories_order_id (repair_order_id),
  KEY idx_repair_order_status_histories_created_at (created_at),
  CONSTRAINT fk_repair_order_status_histories_order FOREIGN KEY (repair_order_id) REFERENCES repair_orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_repair_order_status_histories_user FOREIGN KEY (changed_by) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
